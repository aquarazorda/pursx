// End-to-end tests of the bundled CLI (`npm run build` first).
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const bin = fileURLToPath(new URL("../../bin/pursx.js", import.meta.url));
const pursx = (cwd, ...args) => spawnSync(process.execPath, [bin, ...args], { cwd, encoding: "utf8" });

const tests = [];
const test = (name, fn) => tests.push({ name, fn });

const project = (files) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "pursx-"));
  for (const [file, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    fs.writeFileSync(path.join(dir, file), content);
  }
  return dir;
};

const read = (dir, file) => fs.readFileSync(path.join(dir, file), "utf8");

test("writes a .purs next to each .purx, using the nearest pursx.json", () => {
  const dir = project({
    "pursx.json": '{ "elements": "H" }',
    "src/A.purx": "module A where\nx = <div />\n",
    "src/nested/pursx.json": '{ "elements": "R" }',
    "src/nested/B.purx": "module B where\nx = <div />\n",
  });
  const result = pursx(dir, "src");
  assert.equal(result.status, 0, result.stderr);
  assert.equal(
    read(dir, "src/A.purs"),
    "module A where\nx = (H.div {} [])\n-- Generated by pursx from A.purx. Edit that file instead.\n",
  );
  assert.match(read(dir, "src/nested/B.purs"), /\(R\.div \{\} \[\]\)/);
});

test("leaves an up-to-date file untouched", () => {
  const dir = project({ "A.purx": "module A where\nx = <a />\n" });
  assert.equal(pursx(dir).status, 0);
  const before = fs.statSync(path.join(dir, "A.purs")).mtimeMs;
  assert.equal(pursx(dir).status, 0);
  assert.equal(fs.statSync(path.join(dir, "A.purs")).mtimeMs, before);
});

test("--check fails on a missing or stale file and passes once written", () => {
  const dir = project({ "A.purx": "module A where\nx = <a />\n" });
  const missing = pursx(dir, "--check");
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /A\.purs is out of date/);
  assert.equal(pursx(dir).status, 0);
  assert.equal(pursx(dir, "--check").status, 0);
  fs.writeFileSync(path.join(dir, "A.purx"), "module A where\nx = <b />\n");
  assert.equal(pursx(dir, "--check").status, 1);
});

test("refuses to overwrite a .purs it did not generate", () => {
  const dir = project({ "A.purx": "module A where\nx = <a />\n", "A.purs": "module A where\n" });
  const result = pursx(dir);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /was not generated by pursx/);
  assert.equal(read(dir, "A.purs"), "module A where\n");
});

test("reports errors as path:line:column", () => {
  const dir = project({ "A.purx": "module A where\nx = <div>\n" });
  const result = pursx(dir, "A.purx");
  assert.equal(result.status, 1);
  assert.equal(result.stderr.trim(), "A.purx:2:5: `<div>` is never closed.");
  assert.equal(fs.existsSync(path.join(dir, "A.purs")), false);
});

test("reports a bad config", () => {
  const dir = project({ "pursx.json": '{ "children": 1 }', "A.purx": "x = <a />\n" });
  const result = pursx(dir);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /pursx\.json: `children` must be a string\./);
});

test("--stdout prints without writing", () => {
  const dir = project({ "A.purx": "module A where\nx = <a />\n" });
  const result = pursx(dir, "--stdout", "A.purx");
  assert.equal(result.status, 0);
  assert.equal(result.stdout, "module A where\nx = (a {} [])\n");
  assert.equal(fs.existsSync(path.join(dir, "A.purs")), false);
});

test("--config overrides pursx.json", () => {
  const dir = project({
    "pursx.json": '{ "elements": "H" }',
    "other.json": '{ "elements": "R" }',
    "A.purx": "x = <a />\n",
  });
  assert.equal(pursx(dir, "--config", "other.json", "--stdout", "A.purx").stdout, "x = (R.a {} [])\n");
});

test("skips node_modules, output and hidden directories", () => {
  const dir = project({
    "node_modules/x/A.purx": "x = <a />\n",
    "output/B.purx": "x = <a />\n",
    ".spago/C.purx": "x = <a />\n",
  });
  assert.equal(pursx(dir).status, 0);
  for (const file of ["node_modules/x/A.purs", "output/B.purs", ".spago/C.purs"]) {
    assert.equal(fs.existsSync(path.join(dir, file)), false, file);
  }
});

let failed = 0;
for (const { name, fn } of tests) {
  try {
    fn();
    console.log(`✓ ${name}`);
  } catch (error) {
    failed++;
    console.log(`✗ ${name}\n${error.message}`);
  }
}
console.log(`${tests.length - failed}/${tests.length} CLI tests passed`);
process.exitCode = failed ? 1 : 0;
